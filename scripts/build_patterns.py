#!/usr/bin/env python3
"""Validate patterns.json and generate patterns.md from it.

patterns.json is the single source of truth for the Agent Design Guidelines.
The website reads it directly; patterns.md is the AI-readable version and is
always generated by this script, never edited by hand.

Usage:
  python3 scripts/build_patterns.py            # validate + write patterns.md
  python3 scripts/build_patterns.py --check    # validate only
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "patterns.json"
OUT = ROOT / "patterns.md"
IDS = ROOT / "scripts" / "ids.json"
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def validate(d):
    errors = []

    def need(obj, key, where, kind=str):
        v = obj.get(key)
        if not isinstance(v, kind) or (kind in (str, list) and not v):
            errors.append(f"{where}: '{key}' is missing or empty")
        return v

    for key in ("title", "updated", "site"):
        need(d, key, "top level")
    groups = need(d, "groups", "top level", list) or []
    patterns = need(d, "patterns", "top level", list) or []
    principles = need(d, "principles", "top level", list) or []

    group_ids = set()
    for g in groups:
        gid = need(g, "id", "group")
        need(g, "name", f"group {gid}")
        need(g, "summary", f"group {gid}")
        if gid in group_ids:
            errors.append(f"group id '{gid}' is used twice")
        group_ids.add(gid)

    pattern_ids = set()
    for p in patterns:
        pid = need(p, "id", "pattern") or "?"
        where = f"pattern '{pid}'"
        if not ID_RE.match(pid):
            errors.append(f"{where}: id must be lowercase words joined by hyphens")
        if pid in pattern_ids:
            errors.append(f"pattern id '{pid}' is used twice")
        pattern_ids.add(pid)
        for key in ("name", "rule", "do", "avoid"):
            need(p, key, where)
        if p.get("group") not in group_ids:
            errors.append(f"{where}: group '{p.get('group')}' does not exist")
        for key in ("intro", "look_for"):
            items = need(p, key, where, list) or []
            if any(not isinstance(i, str) or not i.strip() for i in items):
                errors.append(f"{where}: '{key}' has an empty entry")
        ex = p.get("examples")
        if not isinstance(ex, dict):
            errors.append(f"{where}: 'examples' is missing")
            continue
        # A new pattern may have no live examples yet (they need code in index.html).
        items = ex.get("items")
        if not isinstance(items, list):
            errors.append(f"{where} examples: 'items' is missing (use [] if there are no examples yet)")
            items = []
        if items:
            need(ex, "intro", f"{where} examples")
        seen = set()
        for e in items:
            eid = need(e, "id", f"{where} example")
            need(e, "marker", f"{where} example '{eid}'")
            need(e, "what", f"{where} example '{eid}'")
            if eid in seen:
                errors.append(f"{where}: example id '{eid}' is used twice")
            seen.add(eid)

    principle_ids = set()
    for x in principles:
        xid = need(x, "id", "principle") or "?"
        where = f"principle '{xid}'"
        if not ID_RE.match(xid):
            errors.append(f"{where}: id must be lowercase words joined by hyphens")
        if xid in principle_ids:
            errors.append(f"principle id '{xid}' is used twice")
        principle_ids.add(xid)
        need(x, "name", where)
        need(x, "statement", where)
        for c in need(x, "in_practice", where, list) or []:
            for key in ("product", "text", "source"):
                need(c, key, f"{where} in_practice")
        for ref in need(x, "patterns", where, list) or []:
            if ref not in pattern_ids:
                errors.append(f"{where}: links to pattern '{ref}', which does not exist")

    a = need(d, "assessment", "top level", dict) or {}
    levels = need(a, "levels", "assessment", list) or []
    if len(levels) != 3:
        errors.append("assessment: 'levels' must have exactly 3 entries (Not yet, Partly, Yes)")
    question_ids = set()
    for q in need(a, "questions", "assessment", list) or []:
        qid = need(q, "id", "assessment question") or "?"
        where = f"assessment question '{qid}'"
        if qid in question_ids:
            errors.append(f"assessment question id '{qid}' is used twice")
        question_ids.add(qid)
        if q.get("principle") not in principle_ids:
            errors.append(f"{where}: principle '{q.get('principle')}' does not exist")
        need(q, "question", where)
        need(q, "why", where)
        if len(q.get("answers") or []) != 3:
            errors.append(f"{where}: 'answers' must have exactly 3 entries, one per level")
        fixes = q.get("fixes") or []
        if len(fixes) != 2:
            errors.append(f"{where}: 'fixes' must have 2 entries, for Not yet and Partly")
        for f in fixes:
            need(f, "title", f"{where} fix")
            need(f, "ideas", f"{where} fix", list)
        for ref in need(q, "patterns", where, list) or []:
            if ref not in pattern_ids:
                errors.append(f"{where}: links to pattern '{ref}', which does not exist")
    for dm in need(a, "domains", "assessment", list) or []:
        did = need(dm, "id", "assessment domain") or "?"
        for key in ("name", "label", "note"):
            need(dm, key, f"assessment domain '{did}'")
        for k, w in (dm.get("weights") or {}).items():
            if k not in question_ids:
                errors.append(f"assessment domain '{did}': weight for question '{k}', which does not exist")
            if not isinstance(w, (int, float)) or w <= 0:
                errors.append(f"assessment domain '{did}': weight for '{k}' must be a positive number")
    verdicts = need(a, "verdicts", "assessment", list) or []
    if verdicts and verdicts[0].get("from") != 0:
        errors.append("assessment: the first verdict must start 'from' 0")

    # Ids never change: every id in scripts/ids.json must still be here.
    if IDS.exists():
        locked = json.loads(IDS.read_text(encoding="utf-8"))
        now = {
            "groups": group_ids,
            "patterns": pattern_ids,
            "principles": principle_ids,
            "examples": {f"{p.get('id')}/{e.get('id')}" for p in patterns
                         for e in (p.get("examples") or {}).get("items", [])},
            "assessment_questions": question_ids,
            "assessment_domains": {dm.get("id") for dm in a.get("domains") or []},
        }
        for kind, have in now.items():
            for old_id in locked.get(kind, []):
                if old_id not in have:
                    errors.append(
                        f"{kind[:-1].replace('_', ' ')} id '{old_id}' is gone. Ids never change and nothing "
                        f"is deleted: put '{old_id}' back exactly as it was (you can still change its name and text)"
                    )
    return errors


def render(d):
    site = d["site"].rstrip("/") + "/"
    groups = {g["id"]: g for g in d["groups"]}
    used_by = {}
    for x in d["principles"]:
        for ref in x["patterns"]:
            used_by.setdefault(ref, []).append(x)

    build = os.environ.get("GITHUB_SHA", "")[:7]
    out = [
        f"# {d['title']}",
        "",
        f"Updated {d['updated']}. Source: {site}" + (f" (build {build})" if build else ""),
        f"By {', '.join(d.get('authors', []))}." if d.get("authors") else "",
        "",
        "Generated from patterns.json. Do not edit this file by hand.",
        "Cite patterns and principles by their id (in backticks below). Ids never change; names and numbers can.",
        "",
        f"{len(d['principles'])} principles and {len(d['patterns'])} patterns for designing AI agents, "
        "grouped by when they apply: before, while and after the agent acts, and over time.",
        "",
        "## Principles",
        "",
    ]
    for x in d["principles"]:
        out += [
            f"### {x['name']}",
            f"id: `{x['id']}`",
            "",
            x["statement"],
            "",
            "Patterns that put it into practice: "
            + ", ".join(f"`{ref}`" for ref in x["patterns"]),
            "",
            "In practice:",
        ]
        for c in x["in_practice"]:
            tag = " (PITA)" if c.get("pita") else ""
            out.append(f"- {c['product']}{tag}: {c['text']} (source: {c['source']})")
        out.append("")

    out += ["## Patterns", ""]
    n = 0
    for gid, g in groups.items():
        out += [f"### {g['name']}", "", g["summary"], ""]
        for p in (p for p in d["patterns"] if p["group"] == gid):
            n += 1
            out += [
                f"#### {n:02d} {p['name']}",
                f"id: `{p['id']}` · group: {g['name']} · page: {site}#patterns-{p['id']}",
                "",
                f"Rule: {p['rule']}",
                "",
                *[para for t in p["intro"] for para in (t, "")],
                "What to look for:",
                *[f"- {item}" for item in p["look_for"]],
                "",
                f"Do: {p['do']}",
                "",
                f"Avoid: {p['avoid']}",
                "",
                *(["Examples:", *[f"- {e['marker']}: {e['what']}" for e in p["examples"]["items"]], ""]
                  if p["examples"]["items"] else []),
            ]
            if p["id"] in used_by:
                out += [
                    "Principles: "
                    + ", ".join(f"`{x['id']}`" for x in used_by[p["id"]]),
                    "",
                ]

    a = d["assessment"]
    names = {x["id"]: x["name"] for x in d["principles"]}
    lv = a["levels"]
    out += [
        "## Assess your agent",
        "",
        f"One question per principle. Answer each with a level: 0 {lv[0]}, 1 {lv[1]}, 2 {lv[2]}. "
        f"Page: {site}#assess",
        "",
    ]
    for i, q in enumerate(a["questions"], 1):
        out += [
            f"### Q{i}. {q['question']}",
            f"id: `{q['id']}` · principle: `{q['principle']}` ({names[q['principle']]})",
            "",
            *[f"- {n} {lv[n]}: {t}" for n, t in enumerate(q["answers"])],
            "",
            f"Why it matters: {q['why']}",
            "",
        ]
        for n, f in enumerate(q["fixes"]):
            out += [f"If {lv[n]}: {f['title']}", *[f"- {t}" for t in f["ideas"]], ""]
        out += ["Patterns to use: " + ", ".join(f"`{ref}`" for ref in q["patterns"]), ""]
    out += ["### Weights per domain", "", "Every question has weight 1 unless the domain raises it.", ""]
    for dm in a["domains"]:
        w = ", ".join(f"`{k}` ×{v}" for k, v in dm["weights"].items())
        out.append(f"- {dm['name']}: {w}. {dm['note']}")
    out += ["", "Score = round(100 × Σ(weight × level ÷ 2) ÷ Σ(weight)), over the answered questions.", ""]
    for v in a["verdicts"]:
        out.append(f"- From {v['from']}: {v['name']}. {v['meaning']}")
    return "\n".join(line for line in out).rstrip() + "\n"


def main():
    try:
        d = json.loads(SRC.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        sys.exit(f"patterns.json is not valid JSON: {e}")
    errors = validate(d)
    if errors:
        print("patterns.json has problems:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        sys.exit(1)
    print(f"patterns.json OK: {len(d['patterns'])} patterns, {len(d['principles'])} principles")
    if "--check" not in sys.argv:
        OUT.write_text(render(d), encoding="utf-8")
        print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
